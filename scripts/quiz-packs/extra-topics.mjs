const expansionByPack = {
  "Вокруг света": geographyExpansion,
  "Космос и наука": scienceExpansion,
  "Кино, книги и искусство": cultureExpansion,
};

export function expandPackRounds(pack) {
  return {
    ...pack,
    rounds: pack.rounds.map(([name, topics], index) => {
      const newQuestions = new Map(expansionByPack[pack.title][index]);
      return [
        name,
        [
          ...topics,
          ...extraTopics[pack.title][index].map(([title, prompts]) => {
            const questions = newQuestions.get(title);
            if (!questions) throw new Error(`Нет новых вопросов для темы «${title}»`);
            return [
              title,
              [
                ...prompts.map(([prompt, answer, ...alternatives]) =>
                  written(undefined, prompt, answer, ...alternatives),
                ),
                ...questions,
              ],
            ];
          }),
        ],
      ];
    }),
  };
}
